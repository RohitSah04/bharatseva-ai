def seed_additional_schemes() -> None:
    from models.scheme import Scheme
    from app.extensions import db

    existing = {s.name for s in Scheme.query.all()}
    added = 0
    skipped = 0
    for s_data in ADDITIONAL_SCHEMES:
        if s_data["name"] not in existing:
            scheme = Scheme(
                id=_uuid(),
                created_at=_now(),
                updated_at=_now(),
                is_active=1,
                **s_data,
            )
            db.session.add(scheme)
            added += 1
        else:
            skipped += 1

    db.session.commit()
    print(f"Additional schemes: {added} added, {skipped} already existed")
    logger.info("Additional schemes seeded: %d added, %d skipped", added, skipped)


