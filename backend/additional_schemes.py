from __future__ import annotations

import json
import logging
import uuid
from datetime import datetime, timezone

logger = logging.getLogger(__name__)


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _uuid() -> str:
    return str(uuid.uuid4())


def _docs(*names) -> str:
    return json.dumps([{"name": n, "mandatory": True} for n in names])


def _rules(**kwargs) -> str:
    rules = []
    for field, val in kwargs.items():
        if field == "category":
            rules.append({"field": "category", "operator": "in", "values": [val] if isinstance(val, str) else val})
        elif field == "occupation":
            rules.append({"field": "occupation", "operator": "in", "values": [val] if isinstance(val, str) else val})
        elif field == "gender":
            rules.append({"field": "gender", "operator": "eq", "value": val})
        elif field == "max_income":
            rules.append({"field": "annual_income", "operator": "lte", "value": val})
        elif field == "min_age":
            rules.append({"field": "age", "operator": "gte", "value": val})
        elif field == "max_age":
            rules.append({"field": "age", "operator": "lte", "value": val})
    return json.dumps({"logic": "AND", "rules": rules})


